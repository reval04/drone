#define _CRT_SECURE_NO_WARNINGS   // MSVC 보안 경고 억제
#include <stdio.h>                // printf 등
#include "array_list.h"           // 배열 리스트 헤더 포함

/* ════════════════════════════════════════════════════════════
   AL_init : 순차 리스트 초기화
   size를 0으로 설정 → 빈 리스트 상태
   ════════════════════════════════════════════════════════════ */
void AL_init(ArrayList* L) {
    L->size = 0;   // 요소 수를 0으로 초기화 (빈 리스트)
}

/* ════════════════════════════════════════════════════════════
   AL_isFull : 리스트가 가득 찼는지 확인
   ════════════════════════════════════════════════════════════ */
int AL_isFull(ArrayList* L) {
    return L->size == AL_MAX_SIZE;   // 최대 크기이면 1(true) 반환
}

/* ════════════════════════════════════════════════════════════
   AL_isEmpty : 리스트가 비어있는지 확인
   ════════════════════════════════════════════════════════════ */
int AL_isEmpty(ArrayList* L) {
    return L->size == 0;   // 요소 수가 0이면 1(true) 반환
}

/* ════════════════════════════════════════════════════════════
   AL_insertAt : pos 위치에 val 삽입
   pos 이후 요소들을 오른쪽으로 한 칸씩 이동 후 삽입
   ════════════════════════════════════════════════════════════ */
void AL_insertAt(ArrayList* L, int pos, element val) {
    if (AL_isFull(L)) {                        // 리스트가 가득 찬 경우
        printf("[AL 오류] 리스트 가득 참!\n"); // 오류 출력
        return;                                // 함수 종료
    }
    if (pos < 0 || pos > L->size) {            // 유효 범위(0~size) 벗어난 경우
        printf("[AL 오류] 잘못된 위치: %d\n", pos); // 오류 출력
        return;                                // 함수 종료
    }
    for (int i = L->size; i > pos; i--)       // 끝에서부터 pos까지 오른쪽 이동
        L->list[i] = L->list[i - 1];          // 한 칸씩 오른쪽으로 복사
    L->list[pos] = val;                        // pos 위치에 val 저장
    L->size++;                                 // 요소 수 증가
}

/* ════════════════════════════════════════════════════════════
   AL_insertLast : 리스트 맨 끝에 val 삽입
   ════════════════════════════════════════════════════════════ */
void AL_insertLast(ArrayList* L, element val) {
    AL_insertAt(L, L->size, val);   // size 위치(= 마지막 다음)에 삽입
}

/* ════════════════════════════════════════════════════════════
   AL_deleteAt : pos 위치 요소 삭제
   pos 이후 요소들을 왼쪽으로 한 칸씩 이동
   ════════════════════════════════════════════════════════════ */
void AL_deleteAt(ArrayList* L, int pos) {
    if (AL_isEmpty(L)) {                        // 리스트가 비어있는 경우
        printf("[AL 오류] 빈 리스트!\n");       // 오류 출력
        return;                                 // 함수 종료
    }
    if (pos < 0 || pos >= L->size) {            // 유효 범위(0~size-1) 벗어난 경우
        printf("[AL 오류] 잘못된 위치: %d\n", pos); // 오류 출력
        return;                                 // 함수 종료
    }
    for (int i = pos; i < L->size - 1; i++)    // pos부터 끝까지 왼쪽 이동
        L->list[i] = L->list[i + 1];           // 한 칸씩 왼쪽으로 복사
    L->size--;                                  // 요소 수 감소
}

/* ════════════════════════════════════════════════════════════
   AL_indexOf : val의 위치 반환
   선형 탐색으로 첫 번째 일치 위치 반환 (-1 = 없음)
   ════════════════════════════════════════════════════════════ */
int AL_indexOf(ArrayList* L, element val) {
    for (int i = 0; i < L->size; i++)   // 처음부터 끝까지 순회
        if (L->list[i] == val)          // 값 일치하면
            return i;                   // 위치 반환
    return -1;                          // 없으면 -1 반환
}

/* ════════════════════════════════════════════════════════════
   AL_get : pos 위치 요소 반환
   ════════════════════════════════════════════════════════════ */
element AL_get(ArrayList* L, int pos) {
    if (pos < 0 || pos >= L->size) {            // 범위 벗어난 경우
        printf("[AL 오류] 잘못된 위치: %d\n", pos); // 오류 출력
        return (element)0;                       // 기본값 반환
    }
    return L->list[pos];   // pos 위치 요소 반환
}

/* ════════════════════════════════════════════════════════════
   AL_set : pos 위치 요소 값 변경
   ════════════════════════════════════════════════════════════ */
void AL_set(ArrayList* L, int pos, element val) {
    if (pos < 0 || pos >= L->size) {            // 범위 벗어난 경우
        printf("[AL 오류] 잘못된 위치: %d\n", pos); // 오류 출력
        return;                                  // 함수 종료
    }
    L->list[pos] = val;   // pos 위치에 val 덮어쓰기
}

/* ════════════════════════════════════════════════════════════
   AL_size : 현재 요소 수 반환
   ════════════════════════════════════════════════════════════ */
int AL_size(ArrayList* L) {
    return L->size;   // size 필드 반환
}

/* ════════════════════════════════════════════════════════════
   AL_print : 리스트 전체 내용 출력 (인덱스 순서)
   ════════════════════════════════════════════════════════════ */
void AL_print(ArrayList* L) {
    printf("[ArrayList] 크기=%d | [ ", L->size); // 크기 출력
    for (int i = 0; i < L->size; i++)            // 모든 요소 순회
        printf("%d ", (int)L->list[i]);           // 각 요소 출력
    printf("]\n");                                // 닫는 괄호
}

/* ════════════════════════════════════════════════════════════
   AL_sortAsc : 오름차순 버블 정렬
   인접한 두 요소를 비교해 앞이 크면 교환
   ════════════════════════════════════════════════════════════ */
void AL_sortAsc(ArrayList* L) {
    int swapped;                               // 교환 발생 여부 플래그
    do {
        swapped = 0;                           // 플래그 초기화
        for (int i = 0; i < L->size - 1; i++) { // 한 패스 수행
            if (L->list[i] > L->list[i + 1]) {  // 앞 요소가 더 크면
                element tmp    = L->list[i];     // 임시 저장
                L->list[i]     = L->list[i + 1]; // 교환
                L->list[i + 1] = tmp;            // 교환 완료
                swapped = 1;                     // 교환 발생 표시
            }
        }
    } while (swapped);   // 교환이 발생한 동안 반복
}

/* ════════════════════════════════════════════════════════════
   AL_sortDesc : 내림차순 버블 정렬
   인접한 두 요소를 비교해 앞이 작으면 교환
   ════════════════════════════════════════════════════════════ */
void AL_sortDesc(ArrayList* L) {
    int swapped;                               // 교환 발생 여부 플래그
    do {
        swapped = 0;                           // 플래그 초기화
        for (int i = 0; i < L->size - 1; i++) { // 한 패스 수행
            if (L->list[i] < L->list[i + 1]) {  // 앞 요소가 더 작으면
                element tmp    = L->list[i];     // 임시 저장
                L->list[i]     = L->list[i + 1]; // 교환
                L->list[i + 1] = tmp;            // 교환 완료
                swapped = 1;                     // 교환 발생 표시
            }
        }
    } while (swapped);   // 교환이 발생한 동안 반복
}

/* ════════════════════════════════════════════════════════════
   AL_clear : 리스트 전체 비우기
   size를 0으로 되돌려 논리적으로 초기화
   ════════════════════════════════════════════════════════════ */
void AL_clear(ArrayList* L) {
    L->size = 0;   // size를 0으로 초기화 (빈 리스트)
}
