#define _CRT_SECURE_NO_WARNINGS   // MSVC 보안 경고 억제
#include <stdio.h>                // printf 등
#include "array_stack.h"          // 배열 스택 헤더 포함

/* ════════════════════════════════════════════════════════════
   AS_init : 배열 스택 초기화
   top을 -1로 설정 → 빈 스택 상태
   ════════════════════════════════════════════════════════════ */
void AS_init(ArrayStack* s) {
    s->top = -1;   // top을 -1로 초기화 (빈 스택)
}

/* ════════════════════════════════════════════════════════════
   AS_isFull : 스택이 가득 찼는지 확인
   top이 AS_MAX_SIZE - 1이면 가득 찬 상태
   ════════════════════════════════════════════════════════════ */
int AS_isFull(ArrayStack* s) {
    return s->top == AS_MAX_SIZE - 1;   // 최대 인덱스이면 1(true) 반환
}

/* ════════════════════════════════════════════════════════════
   AS_isEmpty : 스택이 비어있는지 확인
   top이 -1이면 빈 상태
   ════════════════════════════════════════════════════════════ */
int AS_isEmpty(ArrayStack* s) {
    return s->top == -1;   // top이 -1이면 1(true) 반환
}

/* ════════════════════════════════════════════════════════════
   AS_push : 스택에 값 삽입
   top을 1 증가시키고 해당 위치에 val 저장
   ════════════════════════════════════════════════════════════ */
void AS_push(ArrayStack* s, element val) {
    if (AS_isFull(s)) {                       // 스택이 가득 찬 경우
        printf("[AS 오류] 스택 오버플로우!\n"); // 오류 메시지 출력
        return;                                // 함수 종료
    }
    s->stack[++s->top] = val;   // top 증가 후 값 저장
}

/* ════════════════════════════════════════════════════════════
   AS_pop : 스택에서 값 꺼내기
   top 위치 값을 반환하고 top을 1 감소
   ════════════════════════════════════════════════════════════ */
element AS_pop(ArrayStack* s) {
    if (AS_isEmpty(s)) {                       // 스택이 비어있는 경우
        printf("[AS 오류] 스택 언더플로우!\n"); // 오류 메시지 출력
        return (element)0;                     // 기본값 반환
    }
    return s->stack[s->top--];   // top 위치 값 반환 후 top 감소
}

/* ════════════════════════════════════════════════════════════
   AS_peek : top 값 조회 (제거 없음)
   ════════════════════════════════════════════════════════════ */
element AS_peek(ArrayStack* s) {
    if (AS_isEmpty(s)) {                   // 스택이 비어있는 경우
        printf("[AS 오류] 빈 스택!\n");    // 오류 메시지 출력
        return (element)0;                 // 기본값 반환
    }
    return s->stack[s->top];   // top 위치 값 반환 (제거 없음)
}

/* ════════════════════════════════════════════════════════════
   AS_size : 현재 저장된 요소 수 반환
   top + 1 = 현재 요소 수
   ════════════════════════════════════════════════════════════ */
int AS_size(ArrayStack* s) {
    return s->top + 1;   // top + 1이 현재 요소 수
}

/* ════════════════════════════════════════════════════════════
   AS_print : 스택 전체 내용 출력 (bottom → top 순서)
   ════════════════════════════════════════════════════════════ */
void AS_print(ArrayStack* s) {
    printf("[ArrayStack] 크기=%d | ", AS_size(s)); // 크기 출력
    printf("bottom → ");                            // 방향 표시
    for (int i = 0; i <= s->top; i++)              // 0(bottom)부터 top까지 순회
        printf("%d ", (int)s->stack[i]);            // 각 요소 출력
    printf("← top\n");                             // top 방향 표시
}

/* ════════════════════════════════════════════════════════════
   AS_clear : 스택 전체 비우기
   top을 -1로 되돌려 논리적으로 초기화
   ════════════════════════════════════════════════════════════ */
void AS_clear(ArrayStack* s) {
    s->top = -1;   // top을 -1로 되돌려 빈 스택으로 초기화
}
